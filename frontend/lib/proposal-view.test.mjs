// Targeted coverage for the consent screen's payload rendering. There is no
// frontend test runner in this project, so this runs on Node's built-in
// runner with type stripping: `npm run test:proposal-view`.
import assert from "node:assert/strict";
import test from "node:test";
import { duplicateEffect, effectiveFields } from "./proposal-view.ts";

function value(action, payload, label) {
  const field = effectiveFields(action, payload).find((item) => item.label === label);
  assert.ok(field, `expected a "${label}" row for ${action}`);
  return field.value;
}

function rendered(action, payload) {
  return JSON.stringify(effectiveFields(action, payload));
}

test("run shows every field the proposal actually carries", () => {
  const fields = effectiveFields("run", {
    image: "nginx:1.27",
    name: "web",
    ports: [{ host: 8080, container: 80, protocol: "tcp" }],
  });
  const labels = fields.map((field) => field.label);
  for (const label of ["Name", "Image", "Published ports", "Command", "Entrypoint", "Restart policy"]) {
    assert.ok(labels.includes(label), `run is missing ${label}`);
  }
  assert.equal(value("run", { image: "nginx", name: "web" }, "Name"), "web");
  assert.equal(value("run", { image: "nginx", name: "web" }, "Image"), "nginx");
  assert.equal(
    value("run", { image: "nginx", ports: [{ host: 8080, container: 80, protocol: null }] }, "Published ports"),
    "0.0.0.0:8080 → 80/tcp",
  );
  assert.equal(value("run", { image: "nginx", name: "  " }, "Name"), "Generated by Docker");
  assert.equal(value("run", { image: "nginx" }, "Published ports"), "None published");
});

test("published ports show the all-interfaces bind address", () => {
  // docker::run_container hardcodes host_ip 0.0.0.0 (backend/src/docker.rs:693),
  // so the exposure scope belongs on the confirm screen.
  assert.equal(
    value("run", { image: "nginx", ports: [{ host: 8080, container: 80, protocol: "tcp" }] }, "Published ports"),
    "0.0.0.0:8080 → 80/tcp",
  );
  assert.equal(
    value("run", { image: "nginx", ports: [{ host: 3000, container: 3000 }] }, "Published ports"),
    "0.0.0.0:3000 → 3000/tcp",
  );
  assert.equal(
    value(
      "duplicate",
      { name: "web-copy", ports: ["8080:80", "127.0.0.1:9000:9000/udp"] },
      "Published ports",
    ),
    "0.0.0.0:8080 → 80/tcp\n127.0.0.1:9000 → 9000/udp",
  );
  assert.equal(
    value("duplicate", { name: "web-copy", ports: ["expose:80"] }, "Published ports"),
    "80/tcp (exposed only, not published)",
  );
  assert.equal(
    value("duplicate", { name: "web-copy", ports: ["auto:80"] }, "Published ports"),
    "0.0.0.0:<random> → 80/tcp",
  );
});

test("a duplicate replaces the source when the name matches ignoring case", () => {
  // docker::duplicate_or_replace compares with eq_ignore_ascii_case.
  assert.equal(duplicateEffect("web", "abc123", "web"), "replace");
  assert.equal(duplicateEffect("web", "abc123", "Web"), "replace");
  assert.equal(duplicateEffect("WEB", "abc123", "web"), "replace");
  assert.equal(duplicateEffect("web", "abc123", "web-copy"), "copy");
  assert.equal(duplicateEffect("web", "abc123", "web "), "replace");
  assert.equal(duplicateEffect("web", "abc123", ""), "copy");
});

test("the replace warning survives a proposal without the source name", () => {
  // The id identifies the source, so the notice must not disappear with the name.
  assert.equal(duplicateEffect(null, "abc123", "web-copy"), "replace-unknown-source");
  assert.equal(duplicateEffect(undefined, "abc123", "web-copy"), "replace-unknown-source");
  assert.equal(duplicateEffect("  ", "abc123", "web-copy"), "replace-unknown-source");
  // Neither the name nor the id was recorded: nothing to key the warning on.
  assert.equal(duplicateEffect(null, null, "web-copy"), "copy");
});

test("run says where command, entrypoint and restart policy come from", () => {
  for (const label of ["Command", "Entrypoint", "Restart policy"]) {
    assert.match(value("run", { image: "nginx" }, label), /image/);
  }
});

test("settings shows the new name and the effective restart policy", () => {
  const payload = { name: "web", restart_policy: "on-failure", restart_maximum_retry_count: 3 };
  assert.equal(value("settings", payload, "Name"), "web");
  assert.equal(value("settings", payload, "Restart policy"), "on-failure (3 retries)");
  assert.equal(
    value("settings", { name: "web", restart_policy: "always" }, "Restart policy"),
    "always",
  );
  assert.equal(value("settings", { name: "" }, "Name"), "Unchanged");
});

test("duplicate renders proposed values and marks everything else as inherited", () => {
  const payload = {
    name: "web-copy",
    image: "nginx:1.28",
    command: ["nginx", "-g", "daemon off;"],
    ports: ["8080:80"],
    restart_policy: "unless-stopped",
  };
  assert.equal(value("duplicate", payload, "New name"), "web-copy");
  assert.equal(value("duplicate", payload, "Image"), "nginx:1.28");
  assert.equal(value("duplicate", payload, "Published ports"), "0.0.0.0:8080 → 80/tcp");
  assert.equal(value("duplicate", payload, "Command"), "nginx -g daemon off;");
  assert.equal(value("duplicate", payload, "Restart policy"), "unless-stopped");
  assert.match(value("duplicate", payload, "Entrypoint"), /source/);

  const bare = { name: "web-copy" };
  for (const label of ["Image", "Published ports", "Command", "Entrypoint", "Restart policy"]) {
    assert.match(value("duplicate", bare, label), /source/);
  }
  assert.equal(value("duplicate", bare, "Environment keys"), "Inherited from the source");
  assert.equal(value("duplicate", bare, "Label keys"), "Inherited from the source");
  assert.equal(value("duplicate", bare, "Mounts"), "Inherited from the source");
});

test("duplicate never shows environment values, label values or mount sources", () => {
  const payload = {
    name: "web-copy",
    env: [{ key: "DB_PASSWORD", value: "hunter2" }],
    labels: [{ key: "owner", value: "ops-team" }],
    mounts: [{ source: "/srv/private", destination: "/data", mount_type: "bind", read_only: true }],
  };
  const fields = effectiveFields("duplicate", payload);
  const text = JSON.stringify(fields);
  assert.ok(!text.includes("hunter2"), "an environment value leaked");
  assert.ok(!text.includes("ops-team"), "a label value leaked");
  assert.ok(!text.includes("/srv/private"), "a mount source leaked");
  assert.equal(value("duplicate", payload, "Environment keys"), "DB_PASSWORD (values removed)");
  assert.equal(value("duplicate", payload, "Label keys"), "owner (values removed)");
  assert.equal(value("duplicate", payload, "Mounts"), "/data (bind, read-only)");
});

test("recreate and the state actions state that the configuration is unchanged", () => {
  assert.match(value("recreate", { action: "recreate" }, "Configuration"), /unchanged/);
  for (const action of ["start", "stop", "restart"]) {
    assert.match(value(action, { action }, "Configuration"), /Unchanged/);
  }
});

test("an unknown payload key is listed rather than silently dropped", () => {
  const text = rendered("settings", { name: "web", restart_policy: "always", privileged: true });
  assert.ok(text.includes("privileged"), "an unknown field was omitted");
  assert.ok(text.includes("value hidden"), "an unknown field's value was shown");
  assert.ok(!text.includes("\"true\""), "an unknown field's value leaked");
});

test("stack actions leave the payload to the compose diff", () => {
  assert.deepEqual(effectiveFields("stack-update", { project: "shop", compose: "services: {}" }), []);
});

test("an unrecognised action still renders a warning row", () => {
  const fields = effectiveFields("teleport", { anything: 1 });
  assert.ok(fields.some((field) => /Unrecognised action/.test(field.value)));
});
